# Quick Check answers (run it to see each one)

# 1. input() always returns a str
answer = input("Type anything: ")
print(type(answer))          # <class 'str'>

# 2. An escape sequence: \t is a tab, \n is a new line
print("Name:\tMahin\nCourse:\tCST1510")

# 3. / is true division (always a float), // is floor division (rounds down)
print(7 / 2)    # 3.5
print(7 // 2)   # 3
